
-- =====================================================
-- CASA CONTABIL
-- MIGRACAO: MULTIPLOS SERVICOS POR SOLICITACAO
-- =====================================================

BEGIN;

-- =====================================================
-- 01. ITENS DA SOLICITACAO
-- =====================================================

CREATE TABLE IF NOT EXISTS public.solicitacao_itens (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    solicitacao_id BIGINT NOT NULL
        REFERENCES public.solicitacoes(id),

    servico_id BIGINT NOT NULL
        REFERENCES public.servicos(id),

    nome_servico TEXT NOT NULL,

    quantidade INTEGER NOT NULL DEFAULT 1
        CHECK (quantidade BETWEEN 1 AND 100),

    valor_unitario_centavos BIGINT
        CHECK (valor_unitario_centavos >= 0),

    valor_total_centavos BIGINT
        GENERATED ALWAYS AS (
            quantidade * valor_unitario_centavos
        ) STORED,

    modalidade TEXT NOT NULL DEFAULT 'orcamento'
        CHECK (
            modalidade IN (
                'avulso',
                'mensal',
                'orcamento'
            )
        ),

    status TEXT NOT NULL DEFAULT 'aguardando'
        CHECK (
            status IN (
                'aguardando',
                'em_analise',
                'aguardando_documentos',
                'aceito',
                'recusado',
                'em_execucao',
                'concluido',
                'cancelado'
            )
        ),

    dados_simulacao JSONB NOT NULL
        DEFAULT '{}'::JSONB,

    observacoes TEXT,

    motivo_recusa TEXT,

    analisado_por UUID
        REFERENCES auth.users(id),

    analisado_em TIMESTAMPTZ,

    criado_em TIMESTAMPTZ NOT NULL
        DEFAULT NOW(),

    atualizado_em TIMESTAMPTZ NOT NULL
        DEFAULT NOW(),

    UNIQUE (solicitacao_id, servico_id),

    UNIQUE (id, solicitacao_id)

);

-- =====================================================
-- 02. PRESERVAR SOLICITACOES ANTIGAS
-- =====================================================

INSERT INTO public.solicitacao_itens (

    solicitacao_id,
    servico_id,
    nome_servico,
    quantidade,
    modalidade,
    status,
    dados_simulacao,
    observacoes

)

SELECT

    s.id,
    s.servico_id,
    sv.nome,
    1,
    'orcamento',
    'aguardando',
    COALESCE(s.dados_simulacao, '{}'::JSONB),
    s.observacoes

FROM public.solicitacoes s

JOIN public.servicos sv
    ON sv.id = s.servico_id

ON CONFLICT (solicitacao_id, servico_id)
DO NOTHING;

-- =====================================================
-- 03. PERMITIR SOLICITACOES COM VARIOS SERVICOS
-- =====================================================

ALTER TABLE public.solicitacoes

    ALTER COLUMN servico_id DROP NOT NULL;

ALTER TABLE public.solicitacoes

    ADD COLUMN IF NOT EXISTS
        chave_idempotencia UUID;

CREATE UNIQUE INDEX IF NOT EXISTS
    idx_solicitacoes_idempotencia

ON public.solicitacoes(chave_idempotencia)

WHERE chave_idempotencia IS NOT NULL;

-- =====================================================
-- 04. CHECKLIST INDIVIDUAL POR SERVICO
-- =====================================================

ALTER TABLE public.checklist_documentos

    ADD COLUMN IF NOT EXISTS
        solicitacao_item_id BIGINT;

ALTER TABLE public.checklist_documentos

    ADD CONSTRAINT
        checklist_item_solicitacao_fkey

    FOREIGN KEY (
        solicitacao_item_id,
        solicitacao_id
    )

    REFERENCES public.solicitacao_itens (
        id,
        solicitacao_id
    );

-- =====================================================
-- 05. INDICES PARA CONSULTAS
-- =====================================================

CREATE INDEX IF NOT EXISTS
    idx_solicitacao_itens_servico

ON public.solicitacao_itens(servico_id);

CREATE INDEX IF NOT EXISTS
    idx_solicitacao_itens_status

ON public.solicitacao_itens(status);

CREATE INDEX IF NOT EXISTS
    idx_checklist_item

ON public.checklist_documentos(
    solicitacao_item_id
);

-- =====================================================
-- 06. ATUALIZACAO AUTOMATICA DE DATAS
-- =====================================================

CREATE OR REPLACE FUNCTION
    public.cc_atualizar_data()

RETURNS TRIGGER

LANGUAGE plpgsql

SET search_path = ''

AS $$

BEGIN

    NEW.atualizado_em = NOW();

    RETURN NEW;

END;

$$;

DROP TRIGGER IF EXISTS
    trg_solicitacao_itens_atualizado

ON public.solicitacao_itens;

CREATE TRIGGER
    trg_solicitacao_itens_atualizado

BEFORE UPDATE

ON public.solicitacao_itens

FOR EACH ROW

EXECUTE FUNCTION
    public.cc_atualizar_data();

-- =====================================================
-- 07. SEGURANCA
-- =====================================================

ALTER TABLE public.solicitacao_itens

    ENABLE ROW LEVEL SECURITY;

REVOKE ALL

ON TABLE public.solicitacao_itens

FROM PUBLIC, anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE

ON TABLE public.solicitacao_itens

TO service_role;

REVOKE ALL

ON FUNCTION public.cc_atualizar_data()

FROM PUBLIC, anon, authenticated;

REVOKE ALL

ON FUNCTION public.registrar_solicitacao(JSONB)

FROM PUBLIC, anon, authenticated;

GRANT EXECUTE

ON FUNCTION public.registrar_solicitacao(JSONB)

TO service_role;

COMMIT;

